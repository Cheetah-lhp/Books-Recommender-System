export type TKey = keyof (typeof dict)["en"];

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: TKey) => string; dir: "ltr" | "rtl" };

const LanguageContext = createContext<Ctx>({ lang: "en", setLang: () => {}, t: (k) => k, dir: "ltr" });

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem("brs-lang") as Lang | null;
    if (stored === "ar" || stored === "en") setLangState(stored);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem("brs-lang", l);
  }, []);

  const t = useCallback((k: TKey) => dict[lang][k] ?? dict.en[k] ?? k, [lang]);

  const value = useMemo(
    () => ({ lang, setLang, t, dir: (lang === "ar" ? "rtl" : "ltr") as "ltr" | "rtl" }),
    [lang, setLang, t],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export const useI18n = () => useContext(LanguageContext);
